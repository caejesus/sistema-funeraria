-- ============================================================================
-- Schema do Sistema Funerária — reconstruído a partir do uso no código (src/)
-- Rodar em um projeto Supabase novo e vazio (SQL Editor), antes de seed.sql.
--
-- Tabelas: app_users, app_settings, atendimentos, frota, ordens_servico,
--          avaliacoes
-- Realtime: atendimentos, frota, ordens_servico
-- Storage: nenhum bucket é usado pelo código.
-- Auth:    o app NÃO usa supabase.auth — o login é feito contra app_users
--          e todas as requisições chegam ao banco com o papel "anon".
--          Por isso as políticas abaixo liberam anon + authenticated
--          (ver seção RLS).
-- ============================================================================


-- ─── app_users ──────────────────────────────────────────────────────────────
-- useSettings.js / ConfigTab.jsx / AlterarSenhaModal.jsx
-- id é TEXT: o app grava id = String(Date.now()) e o admin padrão tem id "1".
create table if not exists public.app_users (
  id          text primary key,
  name        text not null default '',
  login       text not null unique,          -- upsert onConflict: "login"
  password    text not null default '',      -- texto puro (comparado no client)
  role        text not null default 'ATENDENTE',  -- ADM | ATENDENTE | SUPERVISOR | ...
  funcoes     jsonb not null default '[]'::jsonb, -- ["atendente","motorista","tecnico","apoio"]
  created_at  timestamptz not null default now()
);


-- ─── app_settings ───────────────────────────────────────────────────────────
-- useSettings.js — uma linha por lista: hospitals, cemeteries, coffinColors, cars
create table if not exists public.app_settings (
  id          uuid primary key default gen_random_uuid(),
  key         text not null unique,          -- upsert onConflict: "key"
  items       jsonb not null default '[]'::jsonb,  -- array de strings
  created_at  timestamptz not null default now()
);


-- ─── atendimentos ───────────────────────────────────────────────────────────
-- useAtendimentos.js / AcompanhamentoPublico.jsx
-- O registro completo fica em "dados"; as demais colunas são cópias para filtro.
-- id é BIGINT identity (não uuid): o app lista com .order("id", desc) e conta
-- com essa ordem para mostrar os mais recentes primeiro.
create table if not exists public.atendimentos (
  id                bigint generated by default as identity primary key,
  record_id         text not null unique,    -- id do registro no app (Date.now()); upsert onConflict
  codigo            text,
  falecido          text not null default '',
  responsavel       text not null default '',
  data_atendimento  date,                    -- input type="date" (YYYY-MM-DD) ou null
  status            text not null default 'aberto',
  observacoes       text not null default '',
  dados             jsonb not null default '{}'::jsonb,
  created_at        timestamptz not null default now()
);

-- O realtime de DELETE lê payload.old.record_id, que só vem preenchido
-- com REPLICA IDENTITY FULL (por padrão só viria a PK).
alter table public.atendimentos replica identity full;


-- ─── frota ──────────────────────────────────────────────────────────────────
-- FrotaTab.jsx / useAtendimentos.js — um registro por carro (texto "NOME - PLACA")
create table if not exists public.frota (
  id              uuid primary key default gen_random_uuid(),
  carro           text not null unique,      -- upsert onConflict: "carro"
  status          text not null default 'disponivel',
                  -- disponivel | em_servico | manutencao | sem_combustivel | reservado
  motivo          text not null default '',
  atendimento_id  text references public.atendimentos (record_id) on delete set null,
  updated_by      text not null default '',
  updated_at      timestamptz not null default now(),
  created_at      timestamptz not null default now()
);


-- ─── ordens_servico ─────────────────────────────────────────────────────────
-- useOrdemServico.js
create table if not exists public.ordens_servico (
  id             uuid primary key default gen_random_uuid(),
  record_id      text not null unique,       -- Date.now(); usado em todos os .eq()
  numero         text,                       -- "OS-AAAA-0001"
  status         text not null default 'aguardando_remocao',
                 -- aguardando_remocao | ... | finalizada | cancelada
  falecido       text not null default '',
  local_obito    text not null default '',
  endereco       text not null default '',
  observacoes    text not null default '',
  motorista      text not null default '',
  carro          text not null default '',
  prioridade     text not null default 'normal',
  dados          jsonb not null default '{}'::jsonb,
  convertida_em  timestamptz,
  updated_at     timestamptz not null default now(),
  created_at     timestamptz not null default now()
);


-- ─── avaliacoes ─────────────────────────────────────────────────────────────
-- AcompanhamentoPublico.jsx (insert pela página pública) / AvaliacoesTab.jsx
create table if not exists public.avaliacoes (
  id                        uuid primary key default gen_random_uuid(),
  atendimento_id            text unique      -- 1 avaliação por atendimento (.single())
                            references public.atendimentos (record_id) on delete set null,
  falecido                  text not null default '',
  atendente                 text,
  motorista_remocao         text,
  nota_atendimento          smallint check (nota_atendimento  between 1 and 5),
  nota_velorio              smallint check (nota_velorio      between 1 and 5),
  nota_remocao              smallint check (nota_remocao      between 1 and 5),
  nota_encerramento         smallint check (nota_encerramento between 1 and 5),
  comentario_atendimento    text,
  comentario_velorio        text,
  comentario_remocao        text,
  comentario_encerramento   text,
  media_geral               numeric(3,1),
  conhecia_grupo            text,            -- ja_conhecia | anuncios | indicacao
  primeira_vez              boolean,
  experiencia_primeira_vez  text,
  created_at                timestamptz not null default now()
);


-- ─── Índices auxiliares ─────────────────────────────────────────────────────
create index if not exists ordens_servico_created_at_idx on public.ordens_servico (created_at desc);
create index if not exists avaliacoes_created_at_idx     on public.avaliacoes (created_at desc);
create index if not exists frota_atendimento_id_idx      on public.frota (atendimento_id);


-- ============================================================================
-- RLS
-- O app usa só a anon key e não faz login no Supabase Auth, então TODA
-- requisição (inclusive realtime) chega como "anon". Políticas restritas a
-- "authenticated" deixariam o app sem acesso a nada.
-- Quando o login migrar para supabase.auth, troque "to anon, authenticated"
-- por "to authenticated" — exceto o que a página pública de acompanhamento
-- precisa: select em atendimentos e select/insert em avaliacoes.
-- ============================================================================

alter table public.app_users      enable row level security;
alter table public.app_settings   enable row level security;
alter table public.atendimentos   enable row level security;
alter table public.frota          enable row level security;
alter table public.ordens_servico enable row level security;
alter table public.avaliacoes     enable row level security;

drop policy if exists app_users_rw      on public.app_users;
drop policy if exists app_settings_rw   on public.app_settings;
drop policy if exists atendimentos_rw   on public.atendimentos;
drop policy if exists frota_rw          on public.frota;
drop policy if exists ordens_servico_rw on public.ordens_servico;
drop policy if exists avaliacoes_rw     on public.avaliacoes;

create policy app_users_rw      on public.app_users      for all to anon, authenticated using (true) with check (true);
create policy app_settings_rw   on public.app_settings   for all to anon, authenticated using (true) with check (true);
create policy atendimentos_rw   on public.atendimentos   for all to anon, authenticated using (true) with check (true);
create policy frota_rw          on public.frota          for all to anon, authenticated using (true) with check (true);
create policy ordens_servico_rw on public.ordens_servico for all to anon, authenticated using (true) with check (true);
create policy avaliacoes_rw     on public.avaliacoes     for all to anon, authenticated using (true) with check (true);

grant select, insert, update, delete on all tables    in schema public to anon, authenticated;
grant usage, select                  on all sequences in schema public to anon, authenticated;


-- ============================================================================
-- Realtime (postgres_changes)
-- ============================================================================
alter publication supabase_realtime add table
  public.atendimentos,
  public.frota,
  public.ordens_servico;


